from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path


def build_obsidian_note(
    *,
    title: str,
    summary_path: Path | None = None,
    comparison_path: Path | None = None,
    reduction_path: Path | None = None,
    source_url: str | None = None,
) -> str:
    created = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    sections: list[str] = [
        "---",
        f"title: {title}",
        f"created: {created}",
        "tags:",
        "  - ai-eval",
        "  - value-profile",
        "  - local-report",
        "status: generated",
        "---",
        "",
        f"# {title}",
        "",
        "> [!info]",
        "> This note was generated by ai-output-eval-harness.",
        "",
    ]
    if source_url:
        sections.extend(["## Source", "", f"- [Source article]({source_url})", ""])

    for heading, path in (
        ("Evaluation Summary", summary_path),
        ("Value Profile Comparison", comparison_path),
        ("Value Matrix Reduction", reduction_path),
    ):
        if path is None:
            continue
        sections.extend([f"## {heading}", "", f"Source file: `{path}`", ""])
        sections.append(_read_report_body(path))
        sections.append("")

    return "\n".join(sections).rstrip() + "\n"


def resolve_obsidian_output(*, out: Path | None, vault_dir: Path | None, note_path: str | None) -> Path:
    if vault_dir is None:
        if out is None:
            raise ValueError("--out is required when --vault-dir is not provided")
        return out
    if note_path is None:
        raise ValueError("--note-path is required when --vault-dir is provided")
    candidate = (vault_dir / note_path).resolve()
    vault_root = vault_dir.resolve()
    if not str(candidate).lower().startswith(str(vault_root).lower()):
        raise ValueError("note path must stay within vault-dir")
    if candidate.suffix.lower() != ".md":
        candidate = candidate.with_suffix(".md")
    return candidate


def build_obsidian_base() -> str:
    return """filters:
  and:
    - 'file.hasTag("ai-eval")'
    - 'file.hasTag("value-profile")'

properties:
  status:
    displayName: Status
  created:
    displayName: Created

views:
  - type: table
    name: "Value Profile Reports"
    order:
      - file.name
      - status
      - created
      - file.mtime
"""


def _read_report_body(path: Path) -> str:
    if not path.exists():
        return f"> [!warning]\n> Missing report file: `{path}`"
    text = path.read_text(encoding="utf-8").strip()
    if not text:
        return "> [!warning]\n> Report file was empty."
    return _demote_headings(text)


def _demote_headings(text: str) -> str:
    lines = []
    for line in text.splitlines():
        if line.startswith("#"):
            lines.append("##" + line)
        else:
            lines.append(line)
    return "\n".join(lines)
